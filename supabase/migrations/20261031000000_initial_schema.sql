create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nama text not null default 'Pengguna',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.transaksi (
  id bigint generated by default as identity primary key,
  sync_id uuid not null default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  kategori text not null,
  catatan text not null default '',
  nominal bigint not null check (nominal > 0),
  pemasukan boolean not null,
  tanggal date not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.anggaran (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  kategori text not null,
  batas bigint not null check (batas > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, kategori)
);

alter table public.transaksi
  add column if not exists sync_id uuid;
update public.transaksi set sync_id = gen_random_uuid() where sync_id is null;
alter table public.transaksi
  alter column sync_id set default gen_random_uuid(),
  alter column sync_id set not null,
  alter column user_id set default auth.uid(),
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists updated_at timestamptz not null default now();

alter table public.anggaran
  alter column user_id set default auth.uid(),
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists updated_at timestamptz not null default now();

create or replace function public.selaraskan_profil_pengguna()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, nama)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'nama'), ''), 'Pengguna')
  )
  on conflict (id) do update
  set nama = excluded.nama,
      updated_at = now();
  return new;
end;
$$;

drop trigger if exists selaraskan_profil_pengguna on auth.users;
create trigger selaraskan_profil_pengguna
  after insert or update of raw_user_meta_data on auth.users
  for each row execute function public.selaraskan_profil_pengguna();

create index if not exists transaksi_user_tanggal_idx
  on public.transaksi (user_id, tanggal desc, id desc);
create unique index if not exists transaksi_sync_id_idx
  on public.transaksi (sync_id);

alter table public.profiles enable row level security;
alter table public.transaksi enable row level security;
alter table public.anggaran enable row level security;

drop policy if exists "Users manage their own profile" on public.profiles;
create policy "Users manage their own profile"
  on public.profiles for all to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

drop policy if exists "Users manage their own transactions" on public.transaksi;
create policy "Users manage their own transactions"
  on public.transaksi for all to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Users manage their own budgets" on public.anggaran;
create policy "Users manage their own budgets"
  on public.anggaran for all to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

revoke all on public.profiles, public.transaksi, public.anggaran
  from public, anon;
grant usage on schema public to authenticated;
grant select, insert, update, delete
  on public.profiles, public.transaksi, public.anggaran
  to authenticated;
grant usage, select on sequence
  public.transaksi_id_seq,
  public.anggaran_id_seq
  to authenticated;
